#!/usr/bin/env node
// Scans public/work/<category-slug>/ for media files and regenerates
// app/components/work/categoryMedia.generated.ts. Run via `npm run
// generate:media`, or automatically before `dev`/`build` (see package.json).
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const CATEGORY_SLUGS = [
  "3d-animation",
  "background-animations",
  "grid-animations",
  "hero-animations",
  "hover-effects",
  "mouse-effects",
  "navigation-menus",
  "page-transitions",
  "physics-effects",
  "scroll-animation",
  "svg-animations",
  "text-animations",
  "webgl-threejs-effects",
];

const MEDIA_EXTENSIONS = /\.(mp4|webm|mov|jpg|jpeg|png|webp|gif)$/i;

const publicWorkDir = join(process.cwd(), "public", "work");
const outPath = join(
  process.cwd(),
  "app",
  "components",
  "work",
  "categoryMedia.generated.ts"
);

function humanize(filename) {
  const base = filename.replace(MEDIA_EXTENSIONS, "");
  return base
    .replace(/[-_]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

const media = {};

for (const slug of CATEGORY_SLUGS) {
  const dir = join(publicWorkDir, slug);
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
    media[slug] = [];
    continue;
  }

  const files = readdirSync(dir)
    .filter((file) => MEDIA_EXTENSIONS.test(file))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

  media[slug] = files.map((file) => ({
    name: humanize(file),
    img: `/work/${slug}/${file}`,
  }));
}

const header = `/**
 * AUTO-GENERATED by scripts/generate-category-media.mjs — do not edit by
 * hand. Regenerated automatically before \`npm run dev\`/\`npm run build\`,
 * or manually via \`npm run generate:media\`, from whatever files sit in
 * public/work/<category-slug>/.
 */
import type { Slide } from "@/app/components/marketing/WorkSlider";

export const generatedCategoryMedia: Record<string, Slide[]> = `;

writeFileSync(outPath, `${header}${JSON.stringify(media, null, 2)};\n`);

console.log(`generate-category-media: wrote ${outPath}`);
for (const slug of CATEGORY_SLUGS) {
  console.log(`  ${slug}: ${media[slug].length} file(s)`);
}
